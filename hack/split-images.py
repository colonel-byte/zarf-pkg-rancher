#!/usr/bin/env python3
"""Split Rancher's rancher-images.txt across this repo's Zarf packages.

The seven mirror-rancher-* packages are generated whole. app-rancher is hand-written,
but its version strings and image tags are synced in place, because those are the same
facts the image list carries and are what goes stale on a release bump.

The group table below is the only thing a human maintains. An image that matches
no group is a hard failure, not a warning: that is how a new upstream chart in
the next Rancher release announces itself.

    ./hack/split-images.py 2.15.2
    ./hack/split-images.py 2.15.2 --from /tmp/rancher-images.txt
"""

import argparse
import re
import sys
import urllib.request
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = "zarf-v1alpha1-package-prerequisites-schema.json"
LIST_URL = "https://github.com/rancher/rancher/releases/download/v{v}/rancher-images.txt"

# Repos tagged per Kubernetes minor. Everything else in a group is version-agnostic.
PER_MINOR = re.compile(
    r"^rancher/(system-agent-installer-(rke2|k3s)|rke2-runtime|rke2-upgrade"
    r"|k3s-upgrade|hardened-kubernetes|rke2-cloud-provider):"
)
MINOR = re.compile(r":v?(1\.\d+)\.")

# name, one-line purpose, match. Order matters: first match wins.
GROUPS = [
    (
        "app-rancher",
        "The Rancher server itself -- hand-written; only its versions and tags are synced.",
        r"^rancher/(rancher|shell|rancher-webhook|fleet|fleet-agent"
        r"|remotedialer-proxy|kuberlr-kubectl|ui-plugin-catalog):",
    ),
    (
        "mirror-rancher-cni",
        "Calico, Cilium, multus, whereabouts and flannel, for downstream cluster networking.",
        r"^rancher/(mirrored-calico-|mirrored-cilium-|hardened-calico|hardened-flannel"
        r"|hardened-multus|hardened-whereabouts|hardened-cni-plugins)",
    ),
    (
        "mirror-rancher-observability",
        "The rancher-monitoring and rancher-logging charts: Prometheus, Grafana, fluentd, fluent-bit.",
        r"^rancher/(appco-|prom-prometheus|prometheus-federator|mirrored-prometheus-"
        r"|mirrored-grafana-|mirrored-metrics-server|pushprox|mirrored-kube-logging-"
        r"|mirrored-fluent-)",
    ),
    (
        "mirror-rancher-longhorn",
        "Longhorn and the CSI sidecars it and Harvester depend on.",
        r"^rancher/(mirrored-longhornio-|mirrored-sig-storage-|harvester-csi-driver)",
    ),
    (
        "mirror-rancher-cloudprovider",
        "Hosted-provider operators (AKS/EKS/GKE) and the vSphere, Harvester and kube-vip providers.",
        r"^rancher/(aks-operator|eks-operator|gke-operator|harvester-cloud-provider"
        r"|mirrored-cloud-provider-vsphere|rke2-cloud-provider|mirrored-kube-vip)",
    ),
    (
        "mirror-rancher-security",
        "NeuVector, the CIS benchmark scanner and the compliance operator.",
        r"^rancher/(neuvector-|security-scan|compliance-operator|mirrored-sonobuoy-)",
    ),
    (
        "mirror-rancher-support",
        "backup-restore, SUSE SCC registration, supportability-review and Elemental.",
        r"^rancher/(scc-operator|supportability-review|rancher-csp-adapter"
        r"|backup-restore-operator|mirrored-elemental-)",
    ),
    (
        "mirror-rancher-provisioning",
        "Node agents, the RKE2/K3s runtime, hardened base images and the upgrade controllers.",
        r"^rancher/(system-agent|system-agent-installer-|rancher-agent|kube-api-auth"
        r"|machine|turtles|cluster-api-controller|rke2-runtime|rke2-upgrade|k3s-upgrade"
        r"|system-upgrade-controller|hardened-(kubernetes|etcd|coredns|dns-node-cache"
        r"|addon-resizer|cluster-autoscaler|k8s-metrics-server|traefik|snapshot-controller"
        r"|csi-snapshotter)|klipper-|local-path-provisioner|helm-controller"
        r"|nginx-ingress-controller|kube-webhook-certgen|mirrored-jkroepke-kube-webhook-certgen"
        r"|mirrored-pause|mirrored-coredns-|mirrored-library-|mirrored-bci-micro"
        r"|mirrored-curlimages-curl)",
    ),
]

ZARF = """# yaml-language-server: $schema=https://raw.githubusercontent.com/zarf-dev/zarf/main/zarf.schema.json
# GENERATED by hack/split-images.py -- edit the group table there, not this file.
kind: ZarfPackageConfig
metadata:
  name: {name}
  description: "{desc}"
  version: "{version}"

documentation:
  prerequisites: docs/prerequisites.yaml
  schema: ../schema/{schema}

components:
{components}"""

PREREQS = """# yaml-language-server: $schema=../../schema/{schema}
# GENERATED by hack/split-images.py -- edit the group table there, not this file.
---
apiVersion: colonel-byte.dev/v1alpha1
kind: PackagePrerequisites
metadata:
  package: {name}
  version: {version}
  description: >
    Mirrors images only; it deploys no workload. It needs the Zarf registry to
    push into and nothing else of the cluster.

requires:
  packages:
    # Zarf's registry. `zarf package list` reports the init package as `init`.
    - name: init

provides:
  capabilities:
    - name: {capability}
      version: "{version}"
"""

README = """# {name}

{desc}

Images only - **this package deploys no workload**. Mirroring it makes {count} images pullable; nothing on the cluster changes.

Generated by [`hack/split-images.py`](../hack/split-images.py) from Rancher {version}'s `rancher-images.txt`. Do not hand-edit `zarf.yaml`.

## Components

{table}

## Mirror it

Into the registry your downstream clusters actually reach - which is the point of this package, and is not Zarf's internal nodeport registry:

```bash
zarf package mirror-resources zarf-package-{name}-amd64-{version}.tar.zst \\
  --registry-url registry.example.com --registry-push-username <user>
```

Set Rancher's `systemDefaultRegistry` to that same address, or downstream nodes will try Docker Hub and fail in the air gap.
"""


def md_table(headers, rows):
    """A Markdown table with every cell padded to its column's width, per AGENTS.md."""
    widths = [max(len(r[i]) for r in [headers, *rows]) for i in range(len(headers))]
    line = lambda cells: "| " + " | ".join(c.ljust(w) for c, w in zip(cells, widths)) + " |"
    return "\n".join(
        [line(headers), line(["-" * w for w in widths]), *(line(r) for r in rows)]
    )


def fetch(version, local):
    if local:
        return Path(local).read_text().splitlines()
    with urllib.request.urlopen(LIST_URL.format(v=version)) as r:
        return r.read().decode().splitlines()


def partition(images):
    """Assign every image to exactly one group, or die naming the stragglers."""
    out = defaultdict(list)
    for image in images:
        for name, _, pattern in GROUPS:
            if re.match(pattern, image):
                out[name].append(image)
                break
        else:
            sys.exit(f"unmatched image {image!r} -- add it to a group in {__file__}")
    return out


def components(name, images):
    """One 'images' component, except provisioning, which splits by Kubernetes minor."""
    if name != "mirror-rancher-provisioning":
        return {"images": sorted(images)}
    out = defaultdict(list)
    for image in images:
        minor = MINOR.search(image) if PER_MINOR.match(image) else None
        out[f"k8s-{minor.group(1).replace('.', '-')}" if minor else "common"].append(image)
    return {k: sorted(v) for k, v in sorted(out.items())}


def render(name, desc, version, groups):
    pkg = ROOT / name
    (pkg / "docs").mkdir(parents=True, exist_ok=True)

    blocks, table = [], []
    for comp, imgs in groups.items():
        # Only the base set is required; a minor you do not provision is dead weight.
        required = "true" if comp in ("images", "common") else "false"
        refs = "\n".join(f"      - docker.io/{i}" for i in imgs)
        blocks.append(
            f"  - name: {comp}\n    required: {required}\n    images:\n{refs}\n"
        )
        table.append([f"`{comp}`", str(len(imgs)), "yes" if required == "true" else "no"])

    (pkg / "zarf.yaml").write_text(
        ZARF.format(
            name=name,
            desc=desc,
            version=version,
            schema=SCHEMA,
            components="\n".join(blocks),
        )
    )
    (pkg / "docs" / "prerequisites.yaml").write_text(
        PREREQS.format(
            name=name,
            version=version,
            schema=SCHEMA,
            capability=name.replace("mirror-rancher-", "rancher-downstream-"),
        )
    )
    (pkg / "README.md").write_text(
        README.format(
            name=name,
            desc=desc,
            version=version,
            count=sum(len(v) for v in groups.values()),
            table=md_table(["Component", "Images", "Required"], table),
        )
    )
    return sum(len(v) for v in groups.values())


def sub_once(path, pattern, repl, text):
    """Substitute exactly once, or die: a pattern that stopped matching is a silent no-op."""
    new, n = re.subn(pattern, repl, text, flags=re.M)
    if n != 1:
        sys.exit(f"{path}: expected 1 match for {pattern!r}, found {n}")
    return new


def sync_app_rancher(version, available):
    """Retag app-rancher's hand-written files in place.

    It is hand-written because of its chart, values and comments, but its version
    strings and image tags are the same facts the generated packages get from the
    image list -- left to a human they are what goes stale on a release bump.
    """
    # shortcut: the hand-written READMEs hardcode the version in example tarball
    # names and are not synced; do that here if they start going stale in review.
    by_repo = {i.split(":")[0]: i for i in available}
    pkg = ROOT / "app-rancher"
    changed = []

    zarf = pkg / "zarf.yaml"
    text = zarf.read_text()
    for repo, tag in re.findall(r"^      - docker\.io/(\S+?):(\S+)$", text, re.M):
        want = by_repo.get(repo)
        if want is None:
            sys.exit(f"{zarf}: {repo} is not in Rancher {version}'s image list")
        if want != f"{repo}:{tag}":
            text = text.replace(f"      - docker.io/{repo}:{tag}", f"      - docker.io/{want}")
            changed.append(f"{repo}:{tag} -> {want.split(':', 1)[1]}")
    # metadata.version, then the chart version -- the rancher chart is versioned with the app
    text = sub_once(zarf, r'^  version: ".*"$', f'  version: "{version}"', text)
    text = sub_once(zarf, r"^        version: .*$", f"        version: {version}", text)
    zarf.write_text(text)

    prereqs = pkg / "docs" / "prerequisites.yaml"
    text = prereqs.read_text()
    text = sub_once(prereqs, r"^  version: .*$", f"  version: {version}", text)
    text = sub_once(prereqs, r'^      version: ".*"$', f'      version: "{version}"', text)
    prereqs.write_text(text)

    return changed


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("version", help="Rancher version, e.g. 2.15.2")
    ap.add_argument("--from", dest="local", help="read the image list from a file")
    args = ap.parse_args()

    images = [line.strip() for line in fetch(args.version, args.local) if line.strip()]
    assigned = partition(images)
    assert sum(len(v) for v in assigned.values()) == len(images)

    for name, desc, _ in GROUPS:
        if name == "app-rancher":
            retagged = sync_app_rancher(args.version, assigned[name])
            print(f"{len(assigned[name]):4d}  {name} (hand-written; version and tags synced)")
            for line in retagged:
                print(f"        {line}")
            continue
        n = render(name, desc, args.version, components(name, assigned[name]))
        print(f"{n:4d}  {name}")
    print(f"{len(images):4d}  total")


if __name__ == "__main__":
    main()
